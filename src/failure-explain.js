// tail — последние строки вывода скрипта. Возвращает {kind, short, lines} или null.
// Отдельная чистая функция (без ФС и Electron) — её напрямую гоняет run-tests.js.
function explainScriptFailure(tail) {
  const text = Array.isArray(tail) ? tail.join('\n') : String(tail || '');
  if (!text) return null;
  for (const rule of FAILURE_RULES) {
    if (rule.re.test(text)) return { kind: rule.kind, short: rule.short, lines: rule.lines.slice() };
  }
  return null;
}
