// ВЫЖИМКА ПРОВАЛА (summarizeFailure) — то, что раньше терялось
// ===========================================================================
// Диагноз в базе на 20.08.2026: из 46 упавших установок 44 записаны строкой
// «код 1» и БОЛЬШЕ НИЧЕМ. Не потому, что скрипты молчат — vscode.ps1 прямо перед
// exit 1 печатает «Не установились расширения: …», — а потому что до отчёта
// доезжал ТОЛЬКО код возврата: хвост вывода накапливался (main.js outTail) и
// использовался ровно один раз — попыткой опознать причину по словарю. Не совпало
// ни одно правило — хвост выбрасывался вместе с единственным объяснением.
//
// Здесь хвост превращается в короткую выжимку, которая едет в отчёт ВСЕГДА,
// опознана причина или нет:
//   • код возврата,
//   • ЭТАП — последняя строка-заголовок скрипта («Ставлю расширение …»): у всех
//     наших скриптов заголовок этапа заканчивается многоточием, это их общая
//     конвенция, а не догадка;
//   • последние строки, ПОХОЖИЕ на ошибку (а если таких нет — просто последние).
//
// Длина. Приёмник маяка режет текст ошибки по 300 символов на компонент, поэтому
// выжимка по умолчанию ужимается до 280: всё, что длиннее, просто не доедет.
// Полный хвост остаётся в журнале установки на машине человека.

// Шум, по которому нельзя понять НИЧЕГО: пустые строки, рамки, проценты,
// служебные строки квитанций и чек-листа.
const NOISE_RE = /^[\s=_*.\-–—]*$|^\s*\[?\d{1,3}\s*%|^HM-RECEIPT\b|^CHECK\s+(ok|fail|skip)\b/i;
// Признаки строки, которая говорит о ПРОВАЛЕ, а не о ходе работы.
const ERRISH_RE = /ошибк|не удал|не устан|не смог|не найден|не подтверд|не хватает|отказано|запрещ|провал|прерван|\berror\b|\bfail/i;
const ERRISH_EN_RE = /exception|traceback|denied|refused|cannot|can't|could not|unable|not found|no such|timed? out|fatal|abort|EPERM|EACCES|EBUSY|ENOENT|ENOSPC|exit code/i;
// Этап: заголовки шагов во всех наших скриптах заканчиваются многоточием
// («Проверяю VS Code...», «Ставлю библиотеки из PyPI (онлайн)...»).
const PHASE_RE = /(\.\.\.|…)\s*$/;

function normLines(tail) {
  const arr = Array.isArray(tail) ? tail : String(tail == null ? '' : tail).split(/\r?\n/);
  const out = [];
  for (const raw of arr) {
    const s = String(raw == null ? '' : raw).replace(/\s+/g, ' ').trim();
    if (!s || NOISE_RE.test(s)) continue;
    out.push(s);
  }
  return out;
}

// summarizeFailure(tail, {code, maxChars, maxLines})
//   → { phase, lines, oneLine }
// phase   — этап («Ставлю расширение anthropic.claude-code в VS Code») или '';
// lines   — отобранные строки (для журнала: их печатаем человеку целиком);
// oneLine — та же суть одной строкой под лимит отчёта.
function summarizeFailure(tail, opts) {
  const o = opts || {};
  const maxChars = Math.max(40, Number(o.maxChars) || 280);
  const maxLines = Math.max(1, Number(o.maxLines) || 6);
  const lines = normLines(tail);

  let phase = '';
  for (let i = lines.length - 1; i >= 0; i--) {
    if (PHASE_RE.test(lines[i])) { phase = lines[i].replace(/(\.\.\.|…)\s*$/, '').trim(); break; }
  }

  // Строки про провал ценнее последних: у pip/npm/powershell после ошибки идёт
  // ещё десяток строк уборки, и «просто последние» показали бы именно её.
  const errish = lines.filter((s) => ERRISH_RE.test(s) || ERRISH_EN_RE.test(s));
  const picked = (errish.length ? errish : lines).slice(-maxLines);

  // Собираем строку С КОНЦА: последняя строка провала — самая содержательная
  // («Не установились расширения: …»), а перед ней обычно идут подробности.
  // Обрезание с хвоста выкинуло бы именно вывод, ради которого всё затевалось.
  // Этап в выжимке урезаем: у заголовков есть длинный хвост в скобках («…, от имени
  // пользователя, без прав администратора»), который съедал бы половину лимита,
  // отбирая место у САМОЙ ОШИБКИ. В поле phase этап остаётся целиком.
  let phaseShort = phase.replace(/\s*\([^)]*\)\s*$/, '').trim() || phase;
  if (phaseShort.length > 70) phaseShort = phaseShort.slice(0, 69).trim() + '…';
  const head = 'код ' + (o.code === undefined || o.code === null ? '?' : o.code)
    + (phaseShort ? ' · этап: ' + phaseShort : '');
  let body = '';
  for (let i = picked.length - 1; i >= 0; i--) {
    const next = picked[i] + (body ? ' | ' + body : '');
    if (head.length + 3 + next.length > maxChars) {
      // Хотя бы одну строку показать обязаны — даже если её придётся укоротить.
      if (!body) {
        const room = maxChars - head.length - 3 - 1;
        if (room > 8) body = picked[i].slice(0, room).trim() + '…';
      }
      break;
    }
    body = next;
  }
  const oneLine = body ? head + ' · ' + body : head;
  return { phase, lines: picked, oneLine };
}

