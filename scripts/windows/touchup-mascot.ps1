# touchup-mascot.ps1 — подправка скрепки, которая идёт КАЖДЫЙ раз (Windows).
# Снимает автозапуск прошлых версий установщика, если он наш. Идёт отдельно от
# mascot.ps1 потому, что тот при повторном запуске установщика не выполняется: уже
# установленный компонент в окне выбора снят по умолчанию, и человек, которому скрепку
# ставили до решения владельца 06.10.2026 (строка A26), так и остался бы с автозапуском.
#
# Правила (общие для всех touchup-*): автономный (всё нужное подключает сам), повторный
# запуск ничего не меняет, укладывается в секунды (чтение и, если запись наша, удаление
# одного значения реестра), сети нет, код возврата ВСЕГДА 0 — подправка не вправе
# ронять установку. Одна строка «ОБНОВЛЕНО: …» — и только если что-то изменилось;
# сбой — «[touchup-mascot] пропущено: <причина>».
$ErrorActionPreference = 'Continue'
try {
    if ($env:HM_DRY_RUN) {
        # Холостой прогон ничего не меняет в системе ни при каких условиях.
        Write-Host '[dry-run] touchup-mascot: холостой прогон — автозапуск скрепки не трогаю'
    } else {
        . (Join-Path $PSScriptRoot '_mascot.ps1')
        # Тот же путь, что у mascot.ps1: именно на него указывала запись прошлых версий.
        $dest = Join-Path $env:LOCALAPPDATA 'Programs\ClaudeMascot\claude-mascot.exe'
        $st = Remove-HmMascotOldAutorun 'HKCU:\Software\Microsoft\Windows\CurrentVersion\Run' $dest -Quiet
        if ($st -eq 'removed') {
            Write-Host 'ОБНОВЛЕНО: скрепка — убран автозапуск прошлой установки (при входе в Windows она больше не запускается сама)'
        } elseif ($st -eq 'failed') {
            Write-Host '[touchup-mascot] пропущено: не удалось убрать автозапуск скрепки — выключи его вручную: Диспетчер задач → вкладка «Автозагрузка»'
        }
        # absent и foreign — менять нечего: тишина (чужую запись под тем же именем не трогаем).
    }
} catch {
    Write-Host "[touchup-mascot] пропущено: $($_.Exception.Message)"
}
exit 0
