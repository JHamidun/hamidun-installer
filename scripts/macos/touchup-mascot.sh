#!/usr/bin/env bash
# touchup-mascot.sh — подправка скрепки, которая идёт КАЖДЫЙ раз (macOS).
# Снимает автозапуск (LaunchAgent) прошлых версий установщика, если он наш. Идёт отдельно
# от mascot.sh потому, что тот при повторном запуске установщика не выполняется: уже
# установленный компонент в окне выбора снят по умолчанию, и человек, которому скрепку
# ставили до решения владельца 06.10.2026 (строка A26), так и остался бы с автозапуском.
#
# Правила (общие для всех touchup-*): автономный (всё нужное подключает сам), повторный
# запуск ничего не меняет, укладывается в секунды (проверка одного файла и, если он наш,
# его удаление), сети нет, код возврата ВСЕГДА 0 — подправка не вправе ронять установку.
# Одна строка «ОБНОВЛЕНО: …» — и только если что-то изменилось; сбой — «[touchup-mascot]
# пропущено: <причина>». Намеренно без set -e/-u: любой промах здесь не должен
# оборачиваться ненулевым кодом.
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

touchup_mascot() {
  if [ -n "${HM_DRY_RUN:-}" ]; then
    # Холостой прогон ничего не меняет в системе ни при каких условиях.
    echo "[dry-run] touchup-mascot: холостой прогон — автозапуск скрепки не трогаю"
    return 0
  fi
  # shellcheck source=_mascot.sh
  if ! source "$DIR/_mascot.sh"; then
    echo "[touchup-mascot] пропущено: не удалось подключить общие функции скрепки ($DIR/_mascot.sh)"
    return 0
  fi
  local plist="$HOME/Library/LaunchAgents/com.hamidun.claude-mascot.plist"
  remove_old_mascot_autostart 'com.hamidun.claude-mascot' "$plist" quiet
  case "${MASCOT_OLD_AUTOSTART:-}" in
    removed) echo "ОБНОВЛЕНО: скрепка — убран автозапуск прошлой установки (при входе в систему она больше не запускается сама)" ;;
    failed)  echo "[touchup-mascot] пропущено: не удалось удалить старый автозапуск скрепки — удали файл вручную: $plist" ;;
  esac
  # absent и foreign — менять нечего: тишина (чужой файл под тем же именем не трогаем).
  return 0
}

touchup_mascot || echo "[touchup-mascot] пропущено: непредвиденный сбой"
exit 0
