#!/usr/bin/env bash
# _mascot.sh — общие функции скрепки (macOS). Подключается source-ом из mascot.sh
# (установка) и touchup-mascot.sh (подправка при каждом запуске установщика).
# Библиотека: при подключении ничего не запускает и не пишет.
#
# ЗАЧЕМ ОТДЕЛЬНО. Правило «чей это автозапуск» обязано жить в одном месте: два экземпляра
# разойдутся молча — один начнёт снимать чужое, другой перестанет снимать своё. А сам
# mascot.sh при повторном запуске установщика не выполняется вовсе: уже установленный
# компонент в окне выбора снят по умолчанию. Поэтому уборка автозапуска прошлых версий
# вынесена так, чтобы её мог позвать скрипт, который идёт каждый раз (touchup-mascot.sh).

# remove_old_mascot_autostart <label> <plist> [quiet]
#
# Решение владельца 06.10.2026 (строка A26 разбора диалогов поддержки): скрепка больше не
# стартует при входе. Прошлые версии установщика ставили LaunchAgent com.hamidun.claude-mascot
# с RunAtLoad. Снимаем его, но ТОЛЬКО свой: обычный файл (не ссылка) по нашему точному пути
# И с нашей меткой внутри. Чужой файл под этим именем не трогаем — и пишем об этом.
#
# Исход — в переменной MASCOT_OLD_AUTOSTART: absent | removed | foreign | failed. Без третьего
# аргумента функция сама печатает, что сделала; с ним (quiet) молчит — вызывающий решает, что
# сказать человеку (touchup говорит одну строку и только когда что-то изменилось).
remove_old_mascot_autostart() {
  local label="$1" la="$2" quiet="${3:-}"
  MASCOT_OLD_AUTOSTART=absent
  [ -e "$la" ] || [ -L "$la" ] || return 0     # автозапуска не было — молчим
  if [ -L "$la" ] || [ ! -f "$la" ] || ! grep -qF "$label" "$la" 2>/dev/null; then
    MASCOT_OLD_AUTOSTART=foreign
    [ -n "$quiet" ] || echo "  $la — не наш автозапуск скрепки, не трогаю."
    return 0
  fi
  launchctl unload "$la" 2>/dev/null || true
  rm -f "$la" 2>/dev/null || true
  # Итог — по файловой системе: нет plist — нет автозапуска при следующем входе.
  if [ -e "$la" ] || [ -L "$la" ]; then
    MASCOT_OLD_AUTOSTART=failed
    [ -n "$quiet" ] || echo "  ВНИМАНИЕ: старый автозапуск скрепки удалить не удалось — удали файл вручную: $la"
  else
    MASCOT_OLD_AUTOSTART=removed
    [ -n "$quiet" ] || echo "  Автозапуск скрепки от прошлой установки снят: при входе в систему она больше не стартует."
  fi
  return 0
}
