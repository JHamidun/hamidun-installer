#!/usr/bin/env bash
# Исправления «на каждый запуск» (диспетчер, macOS) — близнец scripts/windows/_touchups.ps1.
#
# ЗАЧЕМ. Скрипт компонента запускается, только если компонент отмечен; у человека, который
# поставил его раньше, карточка на повторном запуске снята с галочки, и исправление внутри
# скрипта до него не доходит. Всё, что можно починить у УЖЕ установленного, живёт в
# scripts/macos/touchup-<имя>.sh; verify.sh (скрытый шаг, всегда последний, но стартует
# первым делом) зовёт их через hm_run_touchups, а кнопка «Проверить и починить» запускает
# один verify.
#
# КОНТРАКТ touch-up'а: самостоятельный скрипт; идемпотентный; быстрый и без сети (дольше
# 60 с его прерывают); трогает только профиль ТОГО ЖЕ пользователя; печатает «ОБНОВЛЕНО: …»
# только если что-то изменил. Исход прогон не красит: код выхода ребёнка не учитывается,
# а ошибка или таймаут превращаются в строку «[touchup-…] …» в журнале.
#
# КАКИЕ ФАЙЛЫ ЗАПУСКАТЬ — решает СПИСОК ИМЁН в вызове (verify.sh), а не содержимое каталога (F19, разбор безопасности).
# Вызов: hm_run_touchups <каталог> <предел, с> <имя> [<имя> ...]; имя — touchup-<буквы-цифры-дефис> без пути и расширения,
# файл <имя>.sh ищется только в этом каталоге. Раньше запускалось всё, что совпало с touchup-*.sh: новый файл в каталоге
# был готовым слотом исполнения. Теперь лишний файл не запускается никогда, а забытый в списке ловит тест (список обязан
# совпасть с touchup-*.sh в репозитории: test/run-tests.js, раздел u10b). Порядок запуска — порядок списка (в verify.sh он
# тот же, что давала сортировка по имени в локали C: «-» раньше «.», поэтому vscode-owner идёт перед vscode).
# Здесь нет `exit`: это библиотека, её подключают через source.

hm_run_touchups() {
  local dir="${1:-}" limit="${2:-60}" f name out pid waited line
  if [ "$#" -ge 2 ]; then shift 2; else shift "$#"; fi
  [ -d "$dir" ] || return 0
  # Без имён нечего запускать, и это видно в журнале (пустой "$@" под set -u в bash 3.2 macOS — ошибка, а не пустой список).
  [ "$#" -gt 0 ] || { echo "[touchups] пропущено: список имён пуст"; return 0; }
  for name in "$@"; do
    case "$name" in
      touchup-*) ;;
      *) echo "[touchups] пропущено: имя «$name» не строгое (нужно touchup-<буквы-цифры-дефис>)"; continue ;;
    esac
    case "$name" in
      *[!A-Za-z0-9-]*) echo "[touchups] пропущено: имя «$name» не строгое (нужно touchup-<буквы-цифры-дефис>)"; continue ;;   # только буквы, цифры и дефис
    esac
    f="$dir/$name.sh"
    [ -f "$f" ] || { echo "[$name] пропущено: нет файла $name.sh рядом с verify.sh"; continue; }
    out="$(mktemp "${TMPDIR:-/tmp}/hm-touchup.XXXXXX" 2>/dev/null)" || { echo "[$name] не запустился: нет временного файла"; continue; }
    /bin/bash "$f" >"$out" 2>&1 </dev/null &
    pid=$!
    waited=0
    while kill -0 "$pid" 2>/dev/null && [ "$waited" -lt "$limit" ]; do
      sleep 1
      waited=$((waited + 1))
    done
    if kill -0 "$pid" 2>/dev/null; then
      kill "$pid" 2>/dev/null
      sleep 1
      kill -9 "$pid" 2>/dev/null
      echo "[$name] прервано: не уложился в ${limit} с"
    fi
    wait "$pid" 2>/dev/null
    while IFS= read -r line || [ -n "$line" ]; do
      [ -n "$line" ] && echo "$line"
    done <"$out"
    rm -f "$out"
  done
  return 0
}
